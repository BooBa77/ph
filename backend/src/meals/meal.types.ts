/**
 * Единица продукта.
 *
 * - `g` — граммы: крупа, сахар, соль, сыр. Количество в блюде — граммы,
 *   вес единицы 1;
 * - `piece` — штука: шоколадка, батон;
 * - `can` — банка: тушёнка, сгущёнка;
 * - `pack` — упаковка: чай, специи, кисель.
 *
 * Одна единица на продукт, а не «сколько в чём удобно»: раскладка считает
 * вес, а не переводит единицы, и два разных количества одного продукта
 * в одном блюде сломали бы и сумму, и список для магазина.
 */
export const PRODUCT_UNITS = ['g', 'piece', 'can', 'pack'] as const;

export type ProductUnit = (typeof PRODUCT_UNITS)[number];
