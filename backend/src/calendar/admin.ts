/**
 * Кто админ.
 *
 * Решение проекта: список админов захардкожен, а таблица `admin_users`
 * в базе остаётся приманкой — код в неё не смотрит. Смысл в том, что
 * поддельный список учёток отвлекает того, кто получил доступ к базе,
 * и настоящий админ не выдаётся запросом.
 *
 * В коде лежит UUID, а не адрес: репозиторий публичный, и превратить
 * UUID в человека без доступа к базе нельзя.
 *
 * ВАЖНО: это не роль и не право в системе — просто «свой». Понадобится
 * несколько админов или отзыв доступа без деплоя — переедем на env
 * или на настоящие роли.
 */
const ADMIN_USER_IDS = new Set<string>([
  // Трегубов Сергей — единственный живой пользователь, он же владелец проекта.
  '6aa83135-d887-451e-9897-e1ead6b3d280',
]);

/**
 * Список админов наружу — только для тестов.
 *
 * Тест модерации подписывает токен этим UUID: `JwtStrategy` проверяет
 * подпись и в базу не ходит, а `isAdminUser` смотрит только на этот
 * список. Заводить живую учётку в базе для теста не нужно.
 */
export function adminUserIds(): readonly string[] {
  return [...ADMIN_USER_IDS];
}

export function isAdminUser(userId: string): boolean {
  return ADMIN_USER_IDS.has(userId);
}
