/**
 * Общие типы календаря.
 *
 * Лежат отдельным файлом, потому что нужны и entity, и сервисам, и
 * (через API) фронтенду — а импортировать типы из entity в сервисы
 * справочника ради неаккуратно.
 */

/**
 * Тип дня. Значимо только РАБ или ВЫХ, причина отдыха — это метка дня.
 *
 * `short_workday` — предпраздничный день, работа сокращается на час.
 * Важно: это рабочий день, просто короче, поэтому по нему нельзя считать,
 * что человек отдыхал.
 */
export type CalendarDayType = 'workday' | 'weekend' | 'short_workday';

/**
 * Режим работы пользователя — как заполнять его персональный календарь.
 *
 * `cycle` — пятидневка (2/2 и вахты — будущие фичи, там понадобятся
 * параметры цикла); `free` — свободный график; `study` — учёба;
 * `parental` — декрет; `retired` — пенсия.
 */
export type CalendarMode = 'cycle' | 'free' | 'study' | 'parental' | 'retired';
