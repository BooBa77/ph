import { Injectable } from '@nestjs/common';
import { Observable, Subject } from 'rxjs';

/**
 * Что произошло в переписке: пришло сообщение, диалог прочитали,
 * сообщение переписали или удалили.
 *
 * Четырёх видов достаточно обоим экранам. `message` двигает строку ленты
 * (текст, время, непрочитанное) и дописывает открытый диалог; `read` —
 * единственный способ показать «Прочитано» без перезагрузки: отметка
 * прочтения живёт в `conversation_members` и никак иначе не видна;
 * `message_updated` (24.11.2026) — у уже показанного сообщения сменился
 * текст, и вторым сообщением это показывать нельзя. Так делает автосогласие
 * через 72 часа (`settleExpiredCompensations` переписывает `messages.body`
 * уведомления о переводе) и человек, правящий своё сообщение (25.11.2026).
 * `message_deleted` (25.11.2026) — сообщение убрали физически: в открытом
 * диалоге строку надо не перечеркнуть, а убрать, поэтому это отдельный вид,
 * а не `message_updated` с пустым телом.
 *
 * `notifications` (24.11.2026) — сигнал «перечитай уведомления»: появилась
 * карточка, закрылась или ушла в архив. Отдельного потока для уведомлений
 * нет (§14.2 `topics/messages.md`): панель живёт на том же соединении,
 * что и переписка. DTO в кадре нет — только вид.
 */
export type ConversationEventKind =
  | 'message'
  | 'read'
  | 'message_updated'
  | 'message_deleted'
  | 'notifications';

/**
 * Событие переписки для подписчиков потока (SSE).
 *
 * **Почему сигнал, а не `ConversationDto`.** DTO зависит от смотрящего:
 * в нём `unreadCount`, `peer` и `peerLastReadAt` посчитаны для одного
 * человека, и разослать всем один объект значило бы отдать чужое
 * непрочитанное и чужую метку прочтения. Ровно та же причина, по которой
 * `TripEvent` не несёт `TripGearItemDto`. Клиент по `conversationId`
 * находит строку и дотягивает её одним `GET /conversations/:id`.
 *
 * `actorId` нужен клиенту, чтобы **не перечитывать своё же действие**:
 * ответ `POST /messages` уже вернул сообщение, а своя отметка прочтения
 * уже обнулила счётчик. Чужие действия — наоборот, повод обновиться.
 *
 * **У системного `message_updated` человека-актора нет** (24.11.2026): текст
 * переписало автосогласие через 72 часа, а не человек. Поэтому там пустая
 * строка — она не совпадёт ни с чьим id, и событие применят все подписчики,
 * включая того, кто сам открыл «Бухгалтерию» и запустил расчёт. С 25.11.2026
 * тем же видом ходит правка своего сообщения человеком, и у неё `actorId`
 * заполнен: правивший уже применил ответ ручки, второй раз ему не нужно.
 */
export interface ConversationEvent {
  /**
   * id диалога строкой: в базе `bigint`, TypeORM отдаёт его строкой.
   * У вида `notifications` пуст: карточка не всегда привязана к диалогу.
   */
  conversationId: string;
  kind: ConversationEventKind;
  actorId: string;
  at: string;
  /**
   * Только у `message_updated` и `message_deleted`: какое сообщение
   * изменилось или исчезло.
   *
   * У правки вместе с id едет текст, а не «перечитай сам», — в отличие от
   * `message`. Причина в том, что сообщение уже лежит в открытом диалоге:
   * клиенту нужно заменить тело конкретной строки, а история листается
   * страницами по 50, и переписанное сообщение может быть на любой из них.
   * Сам текст от смотрящего не зависит (это `messages.body`), поэтому кадру
   * он не противоречит.
   */
  messageId?: string;
  body?: string;
}

/**
 * Канал событий переписки — **один поток на человека**, память процесса.
 *
 * Зачем: лента и экран диалога обновлялись по фокусу окна и раз в минуту,
 * а открытая переписка — не обновлялась вовсе. Новое сообщение появлялось
 * только после повторного открытия экрана, и разговор двух людей шёл
 * с задержкой до минуты.
 *
 * **Почему на человека, а не на диалог.** Чатов у человека девять, вкладка
 * одна: подписка на каждый диалог — это девять соединений там, где нужно
 * одно. Событие несёт `conversationId`, и клиент сам раскладывает его
 * и по ленте, и по открытому диалогу. Чаты похода едут по этому же потоку:
 * сообщения в них те же самые, а личный диалог к походу не относится —
 * пятого походного потока ради них не заводим.
 *
 * **Почему без Redis.** Процесс бэкенда один (`docker-compose.prod.yml`),
 * горизонтального масштабирования нет. Появится второй инстанс — сюда
 * придёт pg_notify или Redis, и это будет замена одного класса.
 *
 * Ключ — id человека строкой: id в базе — uuid, но строкой он остаётся
 * и в токене, и в DTO, поэтому приведений типа в вызовах нет.
 *
 * `Map` чистится сама: когда уходит последний подписчик, канал удаляется —
 * иначе карта росла бы на каждого человека, заходившего за время жизни
 * процесса.
 */
@Injectable()
export class ConversationEventsService {
  private readonly streams = new Map<string, Subject<ConversationEvent>>();

  /** Поток событий одного человека. Отписка последнего закрывает канал. */
  stream(userId: string): Observable<ConversationEvent> {
    return new Observable<ConversationEvent>((subscriber) => {
      const subject = this.channel(userId);
      const subscription = subject.subscribe(subscriber);

      return () => {
        subscription.unsubscribe();
        if (!subject.observed) this.streams.delete(userId);
      };
    });
  }

  /**
   * Новое сообщение в диалоге — всем, кому он доступен.
   *
   * Автор тоже получает событие: у него может быть вторая вкладка или
   * телефон, и «своё» там определяется по `actorId`, а не по отсутствию
   * кадра. Тот же порядок у событий похода.
   */
  emitMessage(recipientIds: string[], conversationId: string, actorId: string): void {
    this.send(recipientIds, { kind: 'message', conversationId, actorId });
  }

  /**
   * Диалог прочитан — участникам, чтобы «Прочитано» появилось у автора
   * сообщения сразу, а не после следующего обновления ленты.
   */
  emitRead(recipientIds: string[], conversationId: string, actorId: string): void {
    this.send(recipientIds, { kind: 'read', conversationId, actorId });
  }

  /**
   * Текст сообщения переписан — всем участникам диалога.
   *
   * Заказчик (24.11.2026): открытый диалог получателя должен показать новый
   * текст уведомления о переводе сам, без перезагрузки. Событие значит
   * «сообщение изменилось», а не «пришло новое», поэтому `messageId` и
   * `body` едут в кадре.
   *
   * **`actorId` (25.11.2026).** У системного переписывания (автосогласие
   * через 72 часа) человека-актора нет, и `actorId` пустой: «своё действие
   * не перечитываем» сюда не относится, событие применяют все. У правки
   * своего сообщения человеком `actorId` — его id: ответ `PATCH` уже принёс
   * новый текст, и правившему второй раз перечитывать незачем. Собеседнику
   * кадр нужен в обоих случаях.
   */
  emitMessageUpdated(
    recipientIds: string[],
    conversationId: string,
    message: { id: string; body: string },
    actorId = '',
  ): void {
    this.send(recipientIds, {
      kind: 'message_updated',
      conversationId,
      // Пустая строка — «действовала не человек». См. комментарий
      // у `ConversationEvent.actorId`.
      actorId,
      messageId: message.id,
      body: message.body,
    });
  }

  /**
   * Сообщение удалено — всем участникам диалога (25.11.2026).
   *
   * Удаление физическое: строки в `messages` больше нет, и открытый диалог
   * должен убрать её сразу, а не показать пустоту до перезагрузки. `body`
   * здесь не нужен — тела больше нет; `actorId` заполнен всегда, потому что
   * удалить сообщение может только его автор.
   */
  emitMessageDeleted(
    recipientIds: string[],
    conversationId: string,
    messageId: string,
    actorId: string,
  ): void {
    this.send(recipientIds, {
      kind: 'message_deleted',
      conversationId,
      actorId,
      messageId,
    });
  }

  /**
   * Уведомления изменились — получателям.
   *
   * Кадр-сигнал: `kind: 'notifications'`, `conversationId` пуст (карточка
   * не всегда привязана к диалогу — деньги и альманах живут без него),
   * `actorId` пуст: систему человеком не назовёшь, а «своё действие
   * не перечитываем» здесь не работает — карточку изменил тот же человек,
   * который её закрыл, и панель всё равно должна обновиться.
   *
   * Клиент по этому кадру перечитывает `GET /api/notifications` целиком:
   * секции маленькие, а состав карточки зависит от смотрящего
   * (`unreadCount`, `preview`), поэтому DTO в кадр не кладётся.
   */
  emitNotifications(recipientIds: string[]): void {
    this.send(recipientIds, {
      kind: 'notifications',
      conversationId: '',
      actorId: '',
    });
  }

  private send(
    recipientIds: string[],
    payload: Omit<ConversationEvent, 'at'>,
  ): void {
    const at = new Date().toISOString();

    // Один диалог — одна строка на человека: `Set` отсекает повтор, если
    // человек попал и в состав диалога, и в состав похода.
    for (const userId of new Set(recipientIds)) {
      // Нет подписчиков — событие некому отдавать: канал не создаём.
      this.streams.get(userId)?.next({ ...payload, at });
    }
  }

  private channel(userId: string): Subject<ConversationEvent> {
    const existing = this.streams.get(userId);
    if (existing) return existing;

    const created = new Subject<ConversationEvent>();
    this.streams.set(userId, created);

    return created;
  }
}
