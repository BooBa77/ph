/**
 * Ссылки на объекты справочника внутри текста маршрута.
 *
 * В `trips.route_text` объект упоминается как `[[object:42]]` — **только
 * id, без имени**. Имя подставляется при рендере из справочника, поэтому
 * переименование объекта само доезжает до всех маршрутов, а битая ссылка
 * видна сразу, а не притворяется рабочим текстом.
 *
 * Ручной набор таких ссылок запрещён (в интерфейсе это кнопка выбора
 * объекта), но разбор обязан быть устойчивым к мусору: текст приходит
 * с клиента, и `[[object:abc]]` или `[[object:]]` — не повод падать.
 * Несовпавший фрагмент остаётся обычным текстом.
 *
 * Разбор идёт регуляркой, а не markdown-парсером: ссылка — это наш
 * собственный синтаксис, и он не зависит от того, чем мы рендерим GFM.
 */

/**
 * `\d+` без ограничения длины: `id` в базе — `bigint`, и если однажды
 * объектов станет больше, чем влезает в `number`, отвалится не разбор,
 * а приведение. Молча терять ссылку хуже, чем получить её же числом.
 */
const OBJECT_LINK = /\[\[object:(\d+)\]\]/g;

/**
 * Все id объектов, упомянутые в тексте, без повторов и в порядке появления.
 *
 * Повторы схлопываются: «прошли перевал туда и обратно» — это одна связь,
 * а не две. Порядок появления сохранён, чтобы поведение было предсказуемым
 * при отладке, хотя в `trip_route_elements` он и не хранится.
 */
export function extractObjectIds(text: string): number[] {
  const ids = new Set<number>();

  for (const match of text.matchAll(OBJECT_LINK)) {
    const id = Number(match[1]);
    // Number.isSafeInteger отсекает id длиннее 2^53 — такой объект всё равно
    // не существует, а в базу уехало бы испорченное число.
    if (Number.isSafeInteger(id)) {
      ids.add(id);
    }
  }

  return [...ids];
}
