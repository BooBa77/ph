/**
 * Куда едем: туда или обратно.
 *
 * Раньше сторона выводилась из точек маршрута, и это оказалось хрупко:
 * «Иркутск → Витязь» и «Витязь → Иркутск» — единственный способ отличить
 * одну половину подготовки от другой, а обратный выезд часто вообще без
 * точек («как получится»). Теперь сторона — поле, и на экране это две
 * области с своими кнопками.
 */
export const TRANSFER_DIRECTIONS = ['there', 'back'] as const;

export type TransferDirection = (typeof TRANSFER_DIRECTIONS)[number];

/*
 * Заброска — цепочка этапов из обычных карточек.
 *
 * Отдельной сущности у неё нет (решение заказчика 28.10.2026): в карточке
 * живут `chain_id` и номер этапа `stage`, и этого хватает, чтобы собрать
 * «авто → кони → лодка». Права, пассажиры и компенсация у этапа те же,
 * что у одиночной карточки, — новых правил не появляется.
 *
 * **Порядок задаёт дата отправления, а не тип транспорта** (заказчик:
 * «лодка может стоять и между конями, и после них»). `stage` — производное:
 * сервис перенумеровывает цепочку при каждой записи, поэтому номер этапа
 * и порядок по времени не могут разойтись.
 *
 * **Цепочка переплетает стороны.** «Маршруты бывают как в один конец, так
 * и парами» (заказчик): в одной заброске спокойно живут этапы «туда»
 * и «обратно» — сторона у каждого этапа своя, а общая у них только шкала
 * времени. Номер этапа сквозной по всей цепочке.
 *
 * Пара «туда-обратно» зеркалит ровно один этап, и у пары одна оплата:
 * стоимость задаётся на исходной карточке и живёт в обоих концах.
 */

