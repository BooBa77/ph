/**
 * Словари «Трансфера» — вкладки подготовки похода (`transfer.md`).
 *
 * Отдельный файл по тому же правилу, что `trip-gear.types.ts` и
 * `trip.types.ts`: один список нужен сразу в трёх местах — DTO (валидация
 * `@IsIn`), entity (CHECK) и Swagger (`enum`). Копии разошлись бы молча,
 * а CHECK в базе начал бы отбивать значения, которые API уже принимает.
 */
import type { TripTab } from './trip-tabs';

/**
 * Вид заброски — на чём едем в этой строке.
 *
 * Список живёт в коде, а не в таблице: он не меняется от похода к походу,
 * и справочник ради шести строк — это миграция на каждое «а давайте ещё
 * катер». `foot` здесь потому, что «от электрички пешком четыре километра»
 * — такая же часть заброски, как и машина.
 */
export const TRANSFER_MODES = [
  'car',
  'train',
  'bus',
  'horses',
  'foot',
  'other',
] as const;

export type TransferMode = (typeof TRANSFER_MODES)[number];

/**
 * Машина своя или наёмная.
 *
 * `own` — машина участника: водитель есть в составе, и **свою машину он
 * правит сам**. `hired` — наёмный водитель: аккаунта у него нет, поэтому
 * машину правит тот, кому роль дала вкладку. Смешивать нельзя, и это
 * держит CHECK: у наёмной `driver_user_id` пуст, у своей — заполнен.
 */
export const TRANSFER_CAR_OWNERSHIPS = ['own', 'hired'] as const;

export type TransferCarOwnership = (typeof TRANSFER_CAR_OWNERSHIPS)[number];

/** Вкладка, право на правку которой открывает управление строками. */
export const TRANSFER_TAB: TripTab = 'transfer';

/**
 * Чаты похода, которые видит **только состав**.
 *
 * Гостевой доступен всем, кто видит публичный поход; членский, питания
 * и трансфера — только участникам (любого статуса, включая `invited`:
 * приглашённому надо чем-то спросить). Список вынесен сюда, потому что
 * правило проверяется в трёх местах сервиса, и третья копия условия
 * однажды разошлась бы с первыми двумя.
 */
export const PARTICIPANT_ONLY_CHAT_KINDS = [
  'trip_members',
  'trip_meals',
  'trip_transfer',
] as const;
