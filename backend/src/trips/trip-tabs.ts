/**
 * Вкладки страницы похода и права ролей на них.
 *
 * **Список вкладок — код, права — данные.** Десять вкладок описаны картой
 * (`docs/ph/trip-tabs.md`) и меняются вместе с продуктом; их список
 * должен быть в коде, иначе миграция на каждую перестановку. А вот «какая
 * роль что правит» — это данные: завхозов может быть несколько, роли
 * назначают организаторы, и менять матрицу должен человек, а не деплой
 * (см. `seed-role-tabs.mjs`).
 *
 * **Права — это права на правку.** Видят вкладки **все участники** (решение
 * заказчика 21.10.2026): скрывать «Питание» от участника без роли завхоза
 * значит прятать от него подготовку, ради которой он в поход и идёт.
 * Роль отвечает на вопрос «кто ведёт», а не «кому видно».
 *
 * **«Инфо» здесь нет** (решение 21.10.2026): информация живёт в «Гостевой»
 * и она одинакова для участников и гостей; правка — кнопкой
 * «Редактировать» в шапке, а не вкладкой. Место сбора уехало в «Трансфер».
 *
 * Коды вкладок — латиницей, как остальные словари проекта; русские подписи
 * живут на фронте (`frontend/src/types/trips.ts`). Коды `route` и `sport`
 * подписями не совпадают и не должны: 29.10.2026 заказчик назвал их
 * «Ночёвки» (табор) и «Выпуск», а коды остались прежними — они записаны
 * в базе и в правах ролей, и миграция ради слова, которого пользователь
 * не видит, была бы шумом.
 */
export const TRIP_TABS = [
  'guest',
  'members',
  'sport',
  'transfer',
  'route',
  'meals',
  'gear',
  'firstAid',
  'finance',
  'diary',
] as const;

export type TripTab = (typeof TRIP_TABS)[number];

/**
 * Вкладка, доступ к которой проверяется при управлении ролями.
 *
 * «Участники» — не только список людей: роли назначают оттуда, и кто может
 * править состав и роли, тот может править эту вкладку. Так правило одно:
 * организатор (и соорганизатор через матрицу прав) управляет ролями.
 */
export const MEMBERS_TAB: TripTab = 'members';

/**
 * Вкладка, которая есть только у **официального** похода.
 *
 * Код `sport` — исторический: вкладку заводили как «Спорт», а 29.10.2026
 * заказчик назвал её «Выпуск» (выпуск группы на маршрут, зачётный выход
 * по правилам Федерации). Код не переименовывали: он записан в
 * `role_tab_permissions.tab` и в CHECK-е этой таблицы, а на экране не виден;
 * переименование потребовало бы миграции данных ради слова, которого
 * пользователь не видит.
 *
 * Скрытие — правило бэкенда, а не интерфейса: список вкладок собирается
 * здесь (`listTabs`), и пустой вкладки «Выпуск» у обычного похода быть
 * не должно — выпуска у него нет.
 */
export const OFFICIAL_ONLY_TAB: TripTab = 'sport';

/**
 * Вкладка «Ночёвки» — есть только у похода, у которого **есть ночёвки**.
 *
 * Заказчик 29.10.2026: «Закладка Ночёвки должна отображаться только при
 * наличии ночёвок». Пустая вкладка табора не нужна: пока ночей нет, о чём
 * там говорить и что расставлять.
 *
 * Скрытие — опять правило бэкенда, а не интерфейса (`listTabs`): иначе
 * правило видимости жило бы в двух местах и меню могло разойтись с ответом
 * сервера — ровно так, как разошлось бы с «Выпуском» (`OFFICIAL_ONLY_TAB`).
 *
 * **Что считается наличием ночёвок, пока таблицы ночёвок нет.** Вкладка
 * задумана как таблица (район, варианты, кто где спит), но таблица — шаг
 * после макета, поэтому сейчас наличие ночей выводится из дат:
 * - решённые даты (`trips.starts_at`/`ends_at`) — ночей столько, сколько
 *   календарных дней между началом и концом: 29–31 октября дают две ночи;
 * - иначе — прогноз с конкретным числом: у варианта с `day` спрашиваем
 *   минимальную продолжительность, и «2 и больше дней» — это хотя бы одна
 *   ночь. Месяц без числа сроком не считается (`tabs.md` §7).
 *
 * Когда появится `trip_route_nights`, источником станет она, а правило
 * останется тем же по смыслу: нет ни одной ночи — нет и вкладки.
 */
export const NIGHTS_TAB: TripTab = 'route';

/** Код роли организатора — в связке он назначается автоматически. */
export const COORGANIZER_ROLE_CODE = 'coOrganizer';
