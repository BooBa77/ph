/**
 * Справочные списки и типы предметной области походов.
 *
 * Отдельный файл по той же причине, что и `sport-experience.types.ts`:
 * один и тот же список нужен сразу в трёх местах — DTO (валидация `@IsIn`),
 * entity (CHECK-и) и Swagger (`enum`).
 *
 * **Спортивных словарей здесь нет.** Вид спорта, категория сложности и
 * официальность — свойства только спортивных походов, и они уедут
 * в отдельные таблицы вместе со своими словарями. В `trips` остаётся то,
 * что есть у любого похода; когда спортивные таблицы появятся, их словари
 * обязаны быть взяты из `users/sport-experience.types.ts`, а не написаны
 * заново: поход и профиль должны говорить одними словами, иначе фильтр
 * «покажи походы под мой опыт» не сойдётся — человек заполнил «пешеходный,
 * 2 к.с.», а база предложит ему «hiking, 2».
 */

/**
 * Видимость похода.
 *
 * `public` — виден всем зарегистрированным, `private` — только участникам.
 * Отдельного «по ссылке» нет: зарегистрированных немного, а третье
 * состояние пришлось бы объяснять в каждом запросе доступа.
 */
export const TRIP_VISIBILITIES = ['public', 'private'] as const;

export type TripVisibility = (typeof TRIP_VISIBILITIES)[number];

/**
 * Статус подготовки. Это три состояния «как далеко зашла подготовка»,
 * и ничего больше.
 *
 * `ongoing` и `finished` здесь намеренно отсутствуют: они не решение
 * человека, а следствие дат, и вычисляются из `starts_at`/`ends_at`.
 * Хранить их значило бы заводить поле, которое обязано меняться само, —
 * то есть врать, как только поход перенесли.
 */
export const TRIP_STATUSES = ['idea', 'planning', 'decided'] as const;

export type TripStatus = (typeof TRIP_STATUSES)[number];

/**
 * Статус участника.
 *
 * `invited` — пригласили, человек ещё не ответил; `going` — идёт;
 * `maybe` — 50/50; `declined` — не идёт по любой причине, включая
 * «организую, но сам не пойду». Отдельной роли «помощник» нет:
 * роли — про задачи, а не про участие.
 */
export const PARTICIPANT_STATUSES = [
  'invited',
  'going',
  'maybe',
  'declined',
] as const;

export type ParticipantStatus = (typeof PARTICIPANT_STATUSES)[number];

/**
 * Направление тикета: приглашение (организатор → человек) или заявка
 * (человек → организатор). Обе живут в одной таблице — поля те же,
 * разница только в том, кто начал.
 */
export const REQUEST_DIRECTIONS = ['invite', 'apply'] as const;

export type RequestDirection = (typeof REQUEST_DIRECTIONS)[number];

/**
 * Виды чатов похода.
 *
 * Создаются оба сразу при создании похода, даже если поход приватный:
 * чат существует всегда, а кто в него впущен — вопрос доступа, а не
 * наличия строки.
 */
export const CHAT_KINDS = ['trip_guest', 'trip_members'] as const;

export type ChatKind = (typeof CHAT_KINDS)[number];

/**
 * Код роли организатора в справочнике `roles`.
 *
 * Организатор получает эту роль автоматически при создании похода, в одной
 * транзакции с ним. Значение продублировано в `scripts/seed-roles.mjs`:
 * скрипт — это `.mjs`, он не может импортировать TypeScript, поэтому
 * договорённость держится на двух местах. Меняешь код роли — правь оба.
 */
export const ORGANIZER_ROLE_CODE = 'organizer';

/**
 * Что значит «когда» в фильтре списка походов.
 *
 * `ongoing` и `past` считаются по **факту, если он есть**, и только потом
 * по плану: поход, который вышел на маршрут и отметил это, перестаёт быть
 * «предстоящим» независимо от того, что было запланировано. Обратное —
 * поход, у которого план в прошлом, а факта нет, — числится прошедшим:
 * отмечать факт никто не обязан.
 *
 * `undated` — идеи без дат вовсе: «сходим когда-нибудь». Они не попадают
 * ни в предстоящие, ни в прошедшие, и без отдельного значения их было бы
 * не найти.
 */
export const TRIP_WHEN_VALUES = [
  'upcoming',
  'ongoing',
  'past',
  'undated',
] as const;

export type TripWhen = (typeof TRIP_WHEN_VALUES)[number];
