import { Column, Entity, PrimaryGeneratedColumn } from 'typeorm';

/**
 * Роль участника похода — админский справочник.
 *
 * Таблица называется `roles`, а не `role`: `ROLE` — зарезервированное слово
 * PostgreSQL, и таблица с таким именем потребовала бы кавычек в каждом
 * сыром запросе и в psql.
 *
 * Пользователи роли не создают: новая роль («завхоз», «медик», «штурман»,
 * «фотограф», «водитель») — это строка здесь, а не миграция. Обсуждение
 * ролей идёт вне базы.
 *
 * `organizer` и `leader` в справочнике есть оба, и это не дублирование:
 * организатор — автор похода, он не меняется никогда и живёт в
 * `trips.organizer_user_id`; руководитель — тот, кто ведёт группу на
 * маршруте (у официального спортивного похода это отдельное требование),
 * и он может быть другим человеком. Источник правды по организатору —
 * колонка в `trips`, роль `organizer` в связке — производная для удобства
 * выборки «все роли сразу».
 */
@Entity('roles')
export class Role {
  @PrimaryGeneratedColumn({ type: 'bigint' })
  id: string;

  @Column({ type: 'varchar', length: 50, unique: true })
  code: string;

  @Column({ type: 'varchar', length: 100 })
  name: string;
}
