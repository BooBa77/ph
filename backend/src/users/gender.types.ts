/**
 * Пол человека: `m` — мужской, `f` — женский.
 *
 * Поле живёт в профиле, но нужно **только распределению веса рюкзака**
 * (`docs/ph/gear-distribution.md`): доля женщины считается как 0,8 от
 * мужской. Поэтому правила такие:
 *
 * - **по умолчанию `m`** — существующие пользователи получают его
 *   миграцией, и расчёт работает, не дожидаясь, пока все заполнят профиль;
 * - **в публичный профиль не попадает** (`UserPublicProfileDto`): гость
 *   видит имя, аватарку и город, а пол — нет;
 * - **в походе берётся у участника**, а не хранится в походе: это свойство
 *   человека, а не роль, и «в походе» его не меняют.
 *
 * Два значения, а не три: коэффициент в алгоритме ровно два, и третье
 * значение пришлось бы куда-то отнести. Понадобится поправка на детей —
 * это будет третья колонка `age`, а не третье значение пола.
 */
export const USER_GENDERS = ['m', 'f'] as const;

export type UserGender = (typeof USER_GENDERS)[number];
