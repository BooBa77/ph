/**
 * Родные — члены семьи, с которыми общий бюджет и снаряжение (10.11.2026).
 *
 * Заказчик: «Вводим понятие „родные“, это члены семьи, с которыми общий
 * бюджет и снаряжение». Дальше этот список понадобится «Бухгалтерии»
 * (одна касса на семью) и «Снаряжению» (общие вещи), поэтому связь живёт
 * отдельной таблицей, а не заметкой в профиле.
 *
 * ## Одна строка на пару, а не на направление
 *
 * Родство взаимно: если Анна подтвердила, что Иван — родной, то и Иван
 * видит Анну. Поэтому пара хранится **один раз**, в каноническом порядке
 * (`user_a_id < user_b_id`), а кто отправил запрос — отдельная колонка.
 * Второй строки «в обратную сторону» не бывает: иначе два запроса друг
 * другу жили бы одновременно, и вопрос «мы уже родные или ещё нет»
 * решался бы по двум противоречивым записям.
 *
 * ## Статус
 *
 * `pending` — запрос отправлен, но вторая сторона ещё не ответила.
 * `accepted` — родство действует. Отказ удаляет строку целиком: «отклонил»
 * и «не было» для человека одно и то же, а история отказов — не тот
 * аудит, который стоит хранить.
 *
 * **Виртуальный человек** (без аккаунта) подтвердить ничего не может,
 * поэтому родство с ним создаётся сразу `accepted`: им управляет тот же
 * человек, который его завёл.
 */
export const FAMILY_LINK_STATUSES = ['pending', 'accepted'] as const;

export type FamilyLinkStatus = (typeof FAMILY_LINK_STATUSES)[number];

/**
 * Действующий родной — id и имя (10.11.2026, вечер).
 *
 * Нужен там, где родство — не экран «Контактов», а правило: снаряжение
 * родных в походе. Имя приходит вместе с id, чтобы «Снаряжение» подписало
 * чужую вещь («Палатка · Анна»), не заводя второй запрос за составом.
 */
export interface FamilyPerson {
  id: string;
  displayName: string;
}
