/**
 * Родные: связи пар и заявки на объединение семьи (10.11.2026, шаг 2 —
 * 11.11.2026).
 *
 * Заказчик: «Вводим понятие „родные“, это члены семьи, с которыми общий
 * бюджет и снаряжение». С 11.11.2026 у этого два разных объекта:
 *
 * - **`family_links`** — действующее родство. Строка есть — родные, строки
 *   нет — нет. Никаких статусов: «ждёт подтверждения» больше не живёт в паре,
 *   иначе одна и та же мысль хранилась бы в двух таблицах;
 * - **`family_unions`** — заявка на объединение **двух семей целиком**.
 *   Семья — не таблица, а компонента связей, поэтому новый родственник тянет
 *   всю свою компоненту: заявка собирает обе стороны, и семьи сливаются
 *   только после согласия всех (`plan` в `users/family-union.service.ts`).
 *
 * ## Статусы заявки
 *
 * `pending` — висит, кого-то ждём; `accepted` — все согласились, связи и
 * клоны созданы; `declined` — кто-то отказал, ни одной связи не появилось;
 * `cancelled` — инициатор передумал (или участник вышел из семьи). Отказ
 * и отмена — разные причины, и обе остаются в таблице: заявка с составом —
 * это история, а не пара «родные/нет».
 *
 * ## Согласия
 *
 * `pending` / `accepted` / `declined` у каждого участника. Инициатор
 * согласен по умолчанию (он и нажал), остальные — включая **собственную
 * семью инициатора** — отвечают в «Контактах»: у них тоже появляется доступ
 * к чужому снаряжению, и решать это одному человеку нельзя.
 */
export const FAMILY_UNION_STATUSES = [
  'pending',
  'accepted',
  'declined',
  'cancelled',
] as const;

export type FamilyUnionStatus = (typeof FAMILY_UNION_STATUSES)[number];

export const FAMILY_UNION_CONSENTS = [
  'pending',
  'accepted',
  'declined',
] as const;

export type FamilyUnionConsent = (typeof FAMILY_UNION_CONSENTS)[number];

/**
 * Человек в родне — id и имя.
 *
 * Нужен там, где родство — не экран «Контактов», а правило: зеркало правки
 * вещи и клоны снаряжения. Имя приходит вместе с id, чтобы подсказка
 * «Палатка · Анна» не заводила второй запрос за составом.
 */
export interface FamilyPerson {
  id: string;
  displayName: string;
  /**
   * Человек без аккаунта (11.11.2026).
   *
   * Нужен семейному каталогу: клоны вещей создаются только живым родным,
   * у виртуального каталога нет. В «Контактах» флаг приходит другим
   * полем, здесь он нужен правилу, а не экрану.
   */
  isVirtual: boolean;
}
