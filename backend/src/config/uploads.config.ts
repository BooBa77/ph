import { resolve } from 'node:path';

/**
 * Настройки хранения загруженных пользователями файлов.
 *
 * Файлы лежат на диске, не в БД: у пользователя одна аватарка, метаданных
 * почти нет, а раздача статики через nginx/express дешевле, чем выдача
 * байтов из PostgreSQL.
 *
 * В прод-стеке каталог приходит отдельным docker-томом `ph_uploads`,
 * смонтированным только в бэкенд (см. docker-compose.prod.yml).
 */

/**
 * Корень хранилища на диске.
 *
 * Переменная окружения, а не хардкод: в тестах и на нестандартной
 * раскладке каталог нужно увести в сторону. Дефолт `/app/uploads` —
 * это рабочий каталог контейнера (WORKDIR /app в Dockerfile.backend).
 *
 * Путь приводится к абсолютному: относительный зависел бы от cwd
 * процесса, а это разные значения при запуске `node dist/main`
 * и `nest start --watch`.
 */
export const UPLOADS_DIR = resolve(process.env.UPLOADS_DIR ?? '/app/uploads');

/**
 * URL-префикс, по которому бэкенд раздаёт файлы.
 *
 * Совпадает с началом значения `users.avatar_url`, поэтому клиенту
 * достаточно подставить путь в `src` у `<img>` — никакой сборки URL
 * на фронте нет.
 *
 * Почему `/api/uploads`, а не отдельный `/uploads`: все внешние прокси
 * (Vite в dev, хостовый nginx в prod) настроены на префикс `/api/`.
 * Отдельный префикс потребовал бы правок в трёх местах, включая
 * конфиг на сервере, где копии конфигов легко разъезжаются.
 */
export const UPLOADS_URL_PREFIX = '/api/uploads';

/** Подкаталог для аватарок внутри корня хранилища. */
export const AVATARS_DIR = 'avatars';

/**
 * Максимальный размер загружаемого файла — 10 МБ.
 *
 * Ограничение ставится дважды: в multer (чтобы не держать в памяти
 * гигабайты) и в сервисе аватарок (чтобы правило было видно там, где
 * о нём пишут сообщение об ошибке).
 */
export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;

/**
 * Форматы, которые принимаем.
 *
 * SVG в списке нет намеренно: это XML, он умеет носить в себе скрипты
 * и внешние ссылки, а отдаём мы файлы с того же origin, что и приложение.
 *
 * HEIC и HEIF тоже нет — и это не недосмотр. Проверено на настоящих
 * файлах (контрольная сумма сверена с git-объектом): libvips в нашем
 * образе собран с libheif, контейнер он читает и даже отдаёт размеры,
 * но HEVC-кодек — а именно им сжаты фото с айфона — в нём не работает,
 * декодирование пикселей падает. Поэтому HEIC нормализуется на клиенте:
 * iOS и macOS Safari конвертируют его в JPEG сами, ещё на этапе выбора
 * файла, а в Chrome и Firefox на компьютере пользователь получает
 * понятное объяснение (см. frontend/src/utils/imageDecode.ts).
 */
export const ALLOWED_IMAGE_MIME_TYPES = [
  'image/jpeg',
  'image/png',
  'image/webp',
] as const;

/**
 * Сторона квадратной аватарки после обработки, в пикселях.
 *
 * 400, а не 150: картинку всегда лучше уменьшить на странице, чем
 * показывать мылом. Загруженная аватарка нужна не только в кружке 32 px
 * в шапке, но и в кабинете, и в будущих местах вроде превью профиля —
 * на Retina (2–3x) для 80 CSS px нужно 160–240 физических, а для
 * крупного превью и того больше. Файл при этом остаётся webp и весит
 * единицы килобайт: 400×400 с quality 85 — это ~10 КБ против ~3 КБ
 * у 150×150, то есть разница в пределах погрешности вёрстки.
 */
export const AVATAR_SIZE = 400;

/**
 * Качество WebP. 85 — компромисс: на 150×150 разница с 100 не видна,
 * а вес файла в разы меньше.
 */
export const AVATAR_WEBP_QUALITY = 85;

/**
 * Предел числа пикселей во входной картинке — 50 мегапикселей.
 *
 * Защита от «decompression bomb»: файл на 10 МБ может развернуться
 * в 50000×50000 и съесть всю память контейнера. У sharp есть свой
 * дефолт (268 МП), но нам столько не нужно: 50 МП с запасом покрывают
 * любую фотографию с телефона или камеры.
 */
export const MAX_INPUT_PIXELS = 50_000_000;

/**
 * Публичный префикс URL аватарок — то, что уходит в `users.avatar_url`.
 * Дальше путь достраивается как `<userId>/<uuid>.webp`.
 */
export const AVATAR_URL_PREFIX = `${UPLOADS_URL_PREFIX}/${AVATARS_DIR}`;

