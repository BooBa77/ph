import {
  Check,
  Column,
  CreateDateColumn,
  Entity,
  Generated,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';

import { User } from '../../users/entities/user.entity';
import { GearItemAttribute } from './gear-item-attribute.entity';
import { GearType } from './gear-type.entity';

/**
 * Личное снаряжение человека: «палатка, 2.4 кг», «спальник, 900 г».
 *
 * **Каталог пользователя, а не похода.** Один и тот же спальник ездит
 * во все походы, и заводить его заново к каждому — это ровно та работа,
 * от которой каталог и спасает. В походе (вкладка «Снаряжение», Ф7)
 * человек будет **выбирать** из этого списка, а не писать заново.
 *
 * **Тип вместо вида (Stage B, 30.10.2026).** Раньше вещь знала только вид
 * (`kind`) — полку, а не сущность. Теперь у неё обязательная ссылка
 * на `gear_types`: «Палатка», «Топор», «Тент». Тип задаёт набор
 * характеристик, а значения живут в `gear_item_attributes`. Вид убран
 * целиком: `RESTRICT` на типе не даёт удалить тип, под которым есть вещи
 * (архив — можно).
 *
 * **Название (`title`) остаётся обязательным** — решение заказчика
 * 30.10.2026: это название вещи **в личном каталоге**, человек пишет там
 * что угодно, и ограничивать его незачем. В снаряжении похода `title`
 * не участвует: строка собирается из типа, характеристик, веса и хозяина.
 *
 * **Полка каталога — в группе типа (02.11.2026).** Раньше у вещи был
 * обязательный `group_id`, и полку выбирали для каждой вещи отдельно.
 * Заказчик поменял модель: «группировать их [типы] разрешим самостоятельно».
 * Теперь группа — свойство **типа** у человека (`gear_type_groups`),
 * а вещь попадает в группу своего типа. Поэтому `group_id` здесь больше нет:
 * второй источник правды разошёлся бы с первым после первого «перекинуть
 * тип».
 *
 * **Местоположение — свободный текст (02.11.2026).** «У юзера снаряга лежит
 * на балконе и в гараже… кликает на поле местоположения, поле, посмотрев
 * все объекты, предлагает „Гараж“ и „Балкон“, либо пустое поле, где он сам
 * может вписать, например, „дача“». Хранится строкой, а подсказки фронт
 * собирает из уже введённых значений: справочник мест ради этого заводить
 * незачем.
 *
 * **Порядок внутри группы задаёт владелец** (`sort_order`): это второй,
 * личный порядок, а порядок самих групп настраивает админ. Нули у всех
 * старых вещей миграция заменила шагом 10, иначе первая же перестановка
 * меняла бы местами две одинаковые цифры и ничего не двигала.
 *
 * **Вес необязателен, но если указан — то в граммах.** Граммы, а не
 * килограммы с дробью: `numeric` в Node приезжает строкой и утёк бы
 * в JSON строкой, а дробные килограммы в снаряжении всё равно округляют.
 * `NULL` — «вес не знаю»; такой предмет не попадает в сумму рюкзака,
 * и это честнее нуля: ноль означал бы «невесомый».
 *
 * **Зачем вес вообще.** Раскладка и «вес рюкзака» (Ф7) считаются из этих
 * чисел: без них вкладка «Снаряжение» — список слов, а не подготовка.
 *
 * У одного человека может быть два спальника и три палатки: поэтому это
 * не «одна вещь на тип», а обычный список предметов.
 */
@Entity('gear_items')
// Порядок колонок — как в таблице (`owner_user_id` заведён раньше
// `gear_uid`): TypeORM сравнивает индексы по порядку колонок в `pg_attribute`,
// и обратный порядок давал бы вечный дрейф `schema:log`.
@Index('UQ_gear_items_uid_owner', ['ownerUserId', 'gearUid'], { unique: true })
@Index('IDX_gear_items_gear_uid', ['gearUid'])
@Index('IDX_gear_items_owner_type', ['ownerUserId', 'gearTypeId', 'id'])
@Index('IDX_gear_items_owner_trip_only', ['ownerUserId', 'isTripOnly'])
@Index('IDX_gear_items_owner_type_sort', [
  'ownerUserId',
  'gearTypeId',
  'sortOrder',
  'id',
])
@Check(
  'chk_gear_items_weight',
  `"weight_grams" IS NULL OR "weight_grams" > 0`,
)
@Check('chk_gear_items_title', `char_length(btrim("title")) > 0`)
@Check('chk_gear_items_sort', `"sort_order" >= 0`)
// «Пусто» — это `NULL`, а не пробелы: API обрезает, база не даёт сохранить
// строку из одних пробелов. Без этого `@Check` в entity `schema:log`
// предлагал снести ограничение, которое миграция завела.
@Check(
  'chk_gear_items_location',
  `"location" IS NULL OR char_length(btrim("location")) BETWEEN 1 AND 120`,
)
export class GearItem {
  @PrimaryGeneratedColumn({ type: 'bigint' })
  id: string;

  @Column({ name: 'owner_user_id', type: 'uuid' })
  ownerUserId: string;

  @ManyToOne(() => User, { onDelete: 'RESTRICT' })
  @JoinColumn({
    name: 'owner_user_id',
    foreignKeyConstraintName: 'FK_gear_items_owner',
  })
  owner: User;

  /**
   * Ключ **физической** вещи, общий для всех её клонов (11.11.2026).
   *
   * Заказчик: «у родных снаряжение общее». С 11.11.2026 общее — это не
   * доступ к чужой строке, а **свой клон** в каталоге каждого родного:
   * та же палатка лежит у Анны и у Ивана двумя строками с одним `gear_uid`.
   * Ключ не меняется никогда — ни при объединении семьи, ни при выходе
   * из неё, ни при разводе: по нему находятся все клоны вещи.
   *
   * `DEFAULT gen_random_uuid()` — для сырых вставок (тесты, инварианты);
   * сервис выдаёт ключ сам и клонам передаёт ключ источника.
   */
  @Generated('uuid')
  @Column({
    name: 'gear_uid',
    type: 'uuid',
  })
  gearUid: string;

  /**
   * Кто вещь завёл (11.11.2026).
   *
   * Для клона это автор оригинала, а не владелец клона: так видно, чья это
   * вещь. Нужен будущей заявке на объединение семьи: «for each origin-вещь
   * каждой стороны» — upsert клонов по автору. У существующих вещей
   * совпадает с владельцем.
   */
  @Column({ name: 'origin_user_id', type: 'uuid' })
  originUserId: string;

  @ManyToOne(() => User, { onDelete: 'RESTRICT' })
  @JoinColumn({
    name: 'origin_user_id',
    foreignKeyConstraintName: 'FK_gear_items_origin',
  })
  originUser: User;

  /**
   * Мягкое удаление (11.11.2026): вещь убрана из каталога, но осталась
   * в истории походов.
   *
   * Заказчик: «завершённые походы не занимают снаряжение» и архив похода
   * должен уметь сказать «вещь удалена из каталога, но она есть у …».
   * Поэтому строка не удаляется физически: иначе каскады `trip_personal_gear`
   * и `trip_route_sleeping` выдернули бы вещь из прошлых походов, а
   * `trip_gear` (RESTRICT) вообще не дал бы удалить вещь, которая где-то
   * ездила. Удаление ставит `deleted_at` на **активных клонах текущей
   * компоненты связей**; у бывшего родного его копия остаётся.
   */
  @Column({ name: 'deleted_at', type: 'timestamptz', nullable: true })
  deletedAt: Date | null;

  /** Тип вещи: «Палатка», «Топор». Архивный тип у вещи остаётся допустимым. */
  @Column({ name: 'gear_type_id', type: 'integer' })
  gearTypeId: number;

  @ManyToOne(() => GearType, { onDelete: 'RESTRICT' })
  @JoinColumn({
    name: 'gear_type_id',
    foreignKeyConstraintName: 'FK_gear_items_type',
  })
  gearType: GearType;

  /**
   * Где вещь лежит: «балкон», «гараж», «дача».
   *
   * `NULL` — не указано. Пустая строка не хранится: API превращает её
   * в `NULL`, чтобы «пусто» было одним состоянием, а не двумя.
   */
  @Column({ type: 'varchar', length: 120, nullable: true })
  location: string | null;

  /**
   * Личный порядок вещи внутри её группы.
   *
   * Не `id` и не алфавит: «сначала палатка, потом спальник» — решение
   * человека. Стрелки в каталоге меняют местами соседей, и сервер хранит
   * результат здесь. Группа вещи выводится из её типа, поэтому порядок
   * считается по всем вещам типов этой группы.
   */
  @Column({ name: 'sort_order', type: 'integer', default: 0 })
  sortOrder: number;

  /** Название словами: «Палатка на четверых», «Спальник зимний». */
  @Column({ type: 'varchar', length: 120 })
  title: string;

  /** Вес в граммах. `NULL` — не указан (и не считается). */
  @Column({ name: 'weight_grams', type: 'int', nullable: true })
  weightGrams: number | null;

  /**
   * Вещь заведена **в походе и вручную** (30.10.2026) — «бутылка бензина
   * на розжиг», «кусок целлофана на тент». Живёт только в том походе, где
   * её завели, и **личному каталогу не принадлежит**: `GET /api/gear` такие
   * вещи не отдаёт ни владельцу, ни организатору, а в снаряжении похода
   * они видны как обычная строка.
   *
   * Ссылки на поход здесь нет намеренно: вещь и так попадает в поход
   * строкой `trip_gear`, и вторая ссылка на тот же поход разошлась бы
   * с первой после любого переноса. Флаг говорит ровно одно — «каталогу
   * не принадлежит».
   *
   * У виртуального участника каталога нет вовсе, поэтому его вещи
   * **всегда** `true`, и флага «Регулярное» в форме для них нет.
   *
   * Одноразовую вещь убирает код: строка удаляется вместе со строкой
   * `trip_gear` (каскад от участника или ручка удаления вещи из похода),
   * иначе в базе копились бы невидимые никому вещи.
   */
  @Column({ name: 'is_trip_only', type: 'boolean', default: false })
  isTripOnly: boolean;

  /** Комментарий: «проклеена, течёт по шву». */
  @Column({ type: 'varchar', length: 500, nullable: true })
  note: string | null;

  /** Значения характеристик типа: вместимость, модель, объём. */
  @OneToMany(() => GearItemAttribute, (value) => value.gearItem)
  attributes: GearItemAttribute[];

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt: Date;
}
