/**
 * Статус вещи в общественном снаряжении похода.
 *
 * - `proposed` — предложена участником, решения ещё нет;
 * - `approved` — «берём»: вещь едет, участвует в распределении и в весе;
 * - `declined` — «не берём»: решение принято, вещь остаётся строкой
 *   в таблице. Удалять её вместе с отказом неправильно: «эту палатку
 *   обсуждали и не взяли» — это ответ на вопрос, который обязательно
 *   зададут снова.
 *
 * Утверждает тот, кому право роли дало вкладку «Снаряжение» (завхоз,
 * ремонтник, организатор) — см. `tabs.md`. А назначить несущего может
 * любой участник: люди взрослые и договариваются сами.
 */
export const TRIP_GEAR_STATUSES = ['proposed', 'approved', 'declined'] as const;

export type TripGearStatus = (typeof TRIP_GEAR_STATUSES)[number];

/**
 * Секция экрана «Ночёвки», в которую вещь добавили кнопкой «Добавить ещё»
 * (01.11.2026).
 *
 * Заказчик: «Добавить на всех секциях (Палатки, Готовка (3 шт), Спальник)
 * кнопку „Добавить ещё“… выбор из личного снаряжения или добавка вручную
 * незабинденного снаряжения. Например, вкладыш в спальник, грелка, губка
 * для мытья посуды… вообще, может хоть лодку выбрать». То есть вещь
 * показывается **там, где её добавили**, а не там, куда её отнёс тип.
 *
 * Забинденные кнопки секций («Добавить топор», «Добавить котёл») секцию
 * не пишут — их вещи и так понятны по типу, и `route_section` у них `NULL`.
 * Пометка нужна только «Добавить ещё»: без неё лодка исчезла бы после
 * перезагрузки — по типу её ни одна секция не показывает.
 *
 * Коды — контракт фронта (`frontend/src/types/gear.ts`): меняются вместе
 * с ним, не поодиночке.
 */
export const TRIP_GEAR_ROUTE_SECTIONS = [
  'tent',
  'dishes',
  'campfire',
  'stove',
] as const;

export type TripGearRouteSection = (typeof TRIP_GEAR_ROUTE_SECTIONS)[number];

/**
 * Вид раздела внутри «Берём» / «Взял» (05.11.2026).
 *
 * `shared` — раздел общественного снаряжения: видит весь состав, правит
 * тот, кому дали вкладку. `personal` — раздел человека в «Взял»: остальным
 * он не виден вовсе. Разделы живут в `trip_gear_sections`.
 */
export const TRIP_GEAR_SECTION_SCOPES = ['shared', 'personal'] as const;

export type TripGearSectionScope = (typeof TRIP_GEAR_SECTION_SCOPES)[number];
