/**
 * Статус вещи в общественном снаряжении похода.
 *
 * - `proposed` — предложена участником, решения ещё нет;
 * - `approved` — «берём»: вещь едет, участвует в распределении и в весе;
 * - `declined` — «не берём»: решение принято, вещь остаётся строкой
 *   в таблице. Удалять её вместе с отказом неправильно: «эту палатку
 *   обсуждали и не взяли» — это ответ на вопрос, который обязательно
 *   зададут снова.
 *
 * Утверждает тот, кому право роли дало вкладку «Снаряжение» (завхоз,
 * ремонтник, организатор) — см. `tabs.md`. А назначить несущего может
 * любой участник: люди взрослые и договариваются сами.
 */
export const TRIP_GEAR_STATUSES = ['proposed', 'approved', 'declined'] as const;

export type TripGearStatus = (typeof TRIP_GEAR_STATUSES)[number];
