/**
 * Дневник похода — личные записи участника (16.11.2026).
 *
 * Заказчик: «Дневник — это личная закладка, выглядит как большой чат…
 * Дневник ведётся онлайн и оффлайн (синхронизация при возвращении связи)».
 *
 * Запись рождается на устройстве и живёт там до синхронизации, поэтому
 * `id` — UUID, выданный браузером, а времена записи (`createdAt`,
 * `updatedAt`) ставит устройство: в поле важен момент, когда человек
 * писал, а не когда запись доехала до сервера.
 */
export interface TripDiaryEntry {
  /** UUID с устройства: ключ идемпотентности и адрес правки. */
  id: string
  /** Текст в markdown — тот же редактор, что у чатов. */
  body: string
  createdAt: string
  updatedAt: string
  /**
   * Можно ли записи попасть в альманах (22.11.2026).
   *
   * По умолчанию — да (решение заказчика). Поле может отсутствовать
   * в копии, сохранённой до обновления: тогда пометка считается включённой
   * (`!== false`), иначе старый офлайн-кеш молча спрятал бы записи
   * из альманаха.
   */
  sharedWithTrip?: boolean
}

/** Ответ сервера: только мои записи, старые сверху. */
export interface TripDiary {
  entries: TripDiaryEntry[]
}

/**
 * Запись в пачке синхронизации: состояние целиком.
 *
 * `deletedAt` — могильник: удаление в офлайне тоже событие, и сервер
 * должен узнать о нём не меньше, чем о новой записи. Без него старая
 * копия на втором устройстве воскресила бы удалённое.
 *
 * `sharedWithTrip` необязателен на проводе: устройство с прежней версией
 * приложения его не присылает, и сервер читает отсутствие как «как было».
 */
export interface DiarySyncEntry {
  id: string
  body: string
  createdAt: string
  updatedAt: string
  deletedAt?: string | null
  sharedWithTrip?: boolean
}

/**
 * Запись альманаха: запись дневника или воспоминание участника
 * (22.11.2026).
 *
 * Заказчик переделал прежнюю вкладку: альманах — секция «Гостевой»,
 * участник может дописать своё воспоминание с местом вставки (до похода,
 * конкретный день, самый конец), а собирает и чистит его организатор.
 *
 * Два вида строк различаются `kind`:
 *
 * - `diary` — помеченная автором запись дневника. Её день считает экран
 *   по часовому поясу смотрящего, поэтому `placement` и `dayIndex`
 *   у неё `null`;
 * - `memory` — воспоминание: место вставки выбрал автор при создании,
 *   и правка его не меняет.
 */
export type AlmanacPlacement = 'before' | 'day' | 'after'

export interface AlmanacEntry {
  id: string
  kind: 'diary' | 'memory'
  body: string
  createdAt: string
  updatedAt: string | null
  placement: AlmanacPlacement | null
  dayIndex: number | null
  author: {
    userId: string
    displayName: string
    avatarUrl: string | null
  }
  /** Править текст может только автор воспоминания. */
  canEdit: boolean
  /** Удалять строки может только организатор похода. */
  canDelete: boolean
}

/** Альманах похода: строки вперемешку, порядок расставляет экран. */
export interface TripAlmanac {
  tripId: string
  completedAt: string
  /** Смотрящий — участник и может писать воспоминания. */
  canWrite: boolean
  /** Смотрящий — организатор: правит альманах и удаляет строки. */
  canManage: boolean
  entries: AlmanacEntry[]
}

/** Место вставки воспоминания при создании. */
export interface AlmanacEntryPlace {
  placement: AlmanacPlacement
  /** Номер дня похода; нужен только при `placement = 'day'`. */
  dayIndex?: number
}
