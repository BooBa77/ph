// frontend/src/stores/mobileMenu.ts

import { defineStore } from 'pinia'
import { ref } from 'vue'

/**
 * Пункт мобильного меню.
 *
 * Два источника пунктов: разделы сайта (ссылки) и вкладки похода (кнопки,
 * которые переключают содержимое, не меняя адрес). Поэтому пункт умеет и
 * `to`, и `onSelect` — что именно делать, решает тот, кто его положил.
 *
 * `available: false` — вкладка есть, но экрана ещё нет (Ф7): в меню она
 * видна и недоступна, чтобы карта похода читалась целиком.
 */
export interface MobileMenuEntry {
  /** Устойчивый ключ: по нему тесты и подсветка отличают пункты. */
  key: string
  label: string
  /** Имя иконки: из набора меню сайта или из набора вкладок похода. */
  icon: string
  iconSet?: 'site' | 'trip'
  /** Ссылка — у разделов сайта. */
  to?: string
  /** Действие — у вкладок похода. */
  onSelect?: () => void
  /** Активный пункт: подсвечивается. */
  active?: boolean
  /** Есть ли экран. У разделов сайта не задаётся — там всегда есть. */
  available?: boolean
}

/** Что страница положила в меню вместо разделов сайта. */
export interface MobileMenuContext {
  title: string
  items: MobileMenuEntry[]
}

/**
 * Состояние мобильного меню-гамбургера.
 *
 * **Почему отдельный стор, а не props.** Меню открывается кнопкой в шапке,
 * а содержимое ему даёт страница (`TripView` кладёт вкладки похода).
 * Шапка и страница — соседние ветки дерева, и передать вкладки через props
 * значило бы протащить их через `App.vue`. Стор решает это одной записью:
 * страница объявила контекст — меню показывает его; страница ушла и
 * контекст сняла — меню снова показывает разделы сайта.
 *
 * **Почему контекст, а не флаг «я на странице похода».** Флаг пришлось бы
 * выводить из адреса, и меню начало бы знать про маршруты, которые его
 * не касаются. Контекст — это ровно то, что нужно показать; кто его
 * положил, меню не интересует.
 */
export const useMobileMenuStore = defineStore('mobileMenu', () => {
  /** Открыта ли панель. */
  const isOpen = ref(false)

  /** Контекст страницы. `null` — показываем разделы сайта. */
  const context = ref<MobileMenuContext | null>(null)

  function open() {
    isOpen.value = true
  }

  function close() {
    isOpen.value = false
  }

  function toggle() {
    isOpen.value = !isOpen.value
  }

  /** Страница объявляет своё меню (вкладки похода). */
  function setContext(next: MobileMenuContext) {
    context.value = next
  }

  /**
   * Страница ушла: возвращаем разделам сайта их законное место.
   *
   * Панель при этом закрываем: если человек ушёл с похода на главную через
   * открытое меню, оно не должно остаться открытым поверх новой страницы.
   */
  function clearContext() {
    context.value = null
    isOpen.value = false
  }

  return { isOpen, context, open, close, toggle, setContext, clearContext }
})
