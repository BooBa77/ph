import type { GearItem, GearList } from '@/types/gear'

/**
 * Всё, из чего можно взять вещь в поход (11.11.2026).
 *
 * Заказчик: «Один физический предмет — один неизменный `gear_uid`. В каталоге
 * каждого члена семьи лежит свой клон с тем же `gear_uid`». Поэтому общей
 * полки `familyItems` больше нет: вещь родного приходит в `items` обычным
 * клоном, и в поход ставится именно он — со своей строкой, своим весом
 * и своим владельцем.
 *
 * Функция осталась одна на все экраны, где вещь выбирают для похода:
 * «Снаряжение», «Ночёвки» (палатки, спальник, готовка) и «Посуду».
 * Второй склейки не заводим — иначе один экран однажды научился бы
 * фильтровать удалённые вещи, а другой нет.
 */
export function pickableGear(list: GearList): GearItem[] {
  return list.items
}
