import type { GearItem, GearList } from '@/types/gear'

/**
 * Всё, из чего можно взять вещь в поход: своё и снаряжение родных.
 *
 * Заказчик 10.11.2026: «у родных снаряжение общее… В походе родные
 * равноправно могут использовать снаряжение». Каталог при этом остаётся
 * личным: `GET /api/gear` отдаёт мои вещи в `items`, а вещи родных —
 * отдельным списком `familyItems` (у них заполнены `ownerUserId`
 * и `ownerName`). Это и есть общая полка семьи, и нужна она ровно
 * в выборе снаряжения похода.
 *
 * Одна функция на все экраны, где вещь выбирают для похода: «Снаряжение»,
 * «Ночёвки» (палатки, спальник, готовка) и «Посуда». Второй склейки
 * не заводим — иначе один экран однажды показал бы вещи родных,
 * а другой нет.
 */
export function pickableGear(list: GearList): GearItem[] {
  return [...list.items, ...(list.familyItems ?? [])]
}
