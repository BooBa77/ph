/**
 * Проверка, что картинку из выбранного файла браузер действительно может
 * показать.
 *
 * Зачем: аватарка обрабатывается на клиенте — пользователь видит фото
 * в кроппере, а на сервер уходит уже готовый JPEG. Значит, если браузер
 * файл не декодирует, кроппер окажется пустым, и вместо понятной ошибки
 * человек увидит сломанный интерфейс.
 *
 * Главный случай — HEIC с айфона:
 *   - iOS Safari и macOS Safari конвертируют HEIC в JPEG сами, на уровне
 *     выбора файла (проверено: на iOS — всегда, на macOS — если HEIC
 *     не разрешён в accept). До нас такой файл доезжает уже картинкой;
 *   - Chrome, Firefox и Edge на компьютере HEIC не умеют вообще. Вот тут
 *     и нужна честная ошибка вместо пустого экрана;
 *   - бэкенд на HEIC тоже не рассчитывает: libvips в нашем образе собран
 *     с libheif, но HEVC-кодек (это и есть кодек айфона) в нём не
 *     работает — контейнер читается, а пиксели нет. Проверено на двух
 *     настоящих файлах, включая сверку контрольной суммы.
 *
 * Если однажды понадобится принимать HEIC ещё и в Chrome, сюда добавится
 * WASM-декодер (libheif, ~1.2 МБ, грузится только при первом таком файле).
 * Пока это лишний вес: на телефоне, который такие файлы создаёт, они и так
 * превращаются в JPEG.
 */

/** Расширение или тип похожи на HEIC. Нужно только для текста ошибки. */
export function looksLikeHeic(file: File): boolean {
  const type = file.type.toLowerCase()
  const name = file.name.toLowerCase()
  return (
    type.includes('heic') ||
    type.includes('heif') ||
    name.endsWith('.heic') ||
    name.endsWith('.heif')
  )
}

/**
 * Может ли браузер декодировать этот файл.
 *
 * Проверяем именно декодирование, а не тип или расширение: тип в
 * multipart подделывается, а расширение может врать. `createImageBitmap`
 * есть во всех актуальных браузерах; если его нет — не блокируем
 * пользователя, пусть попробует (кроппер сам покажет ошибку).
 */
export async function canBrowserDecode(file: File): Promise<boolean> {
  if (typeof createImageBitmap !== 'function') return true

  try {
    const bitmap = await createImageBitmap(file)
    bitmap.close()
    return true
  } catch {
    return false
  }
}
